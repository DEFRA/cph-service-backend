// Acceptance Criteria

// Where the applicant answers Yes to “Do you own the land”, the application is eligible for permanent CPH landowner route

// Where the applicant answers No, the application does not proceed through this route

// The permanent CPH is issued to the applicant who owns the land

// The CPH uses Location 1 Easting and Northing as the main livestock location

// The County code (CC) and Parish code (PPP) derived from location 1 are used to create the CPH number

// The Holding number is allocated sequentially from the next available number in the permanent series (0001-4999)

// The CPH number is created in the format CC/PPP/HHHH

// The start date is the date the CPH is created And no end date is assigned

// The successfully created CPH has a status of Active

// Where all the location and other checks have not passed, the permanent CPH is not created and is routed for manual review
